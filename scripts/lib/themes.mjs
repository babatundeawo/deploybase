// Turns data/themes.json into assets/css/themes.css and checks the colours.
//
// Each theme lists its light colours. The dark colours are worked out from them
// (same hue, dark tinted surfaces, lighter brand colours) unless the theme gives
// its own "dark" values. Every text and background pair is then checked against
// WCAG 2.2 AA (4.5:1 for text) in both schemes.

import { contrast, ensureContrast, hexToOklch, mix, oklchToHex, readableOn } from "./color.mjs";

const SYSTEM_MONO = 'ui-monospace, "SF Mono", Menlo, Consolas, monospace';
const SYSTEM_SANS = 'system-ui, -apple-system, "Segoe UI", Roboto, sans-serif';
const SYSTEM_SERIF = 'Georgia, "Times New Roman", serif';
const TOKENS = ["bg", "surface", "surface-2", "ink", "ink-soft", "line", "primary", "primary-ink", "accent", "accent-2"];

function deriveDark(light) {
  const p = hexToOklch(light.primary);
  const a = hexToOklch(light.accent);
  // Tint the dark surfaces with whichever brand colour has more colour in it.
  const hue = p.C >= 0.04 ? p.h : a.h;
  const tint = (L, C) => oklchToHex({ L, C, h: hue });

  const bg = tint(0.17, 0.022);
  const surface = tint(0.215, 0.026);
  const surface2 = tint(0.26, 0.03);
  const line = tint(0.335, 0.03);
  const ink = tint(0.95, 0.008);
  const inkSoft = tint(0.78, 0.022);

  const soft = (hex) => mix(hex, surface, 8);
  const brand = (hex, floor) => {
    const o = hexToOklch(hex);
    o.L = Math.max(o.L, floor);
    const lifted = oklchToHex(o);
    return ensureContrast(lifted, [bg, surface, surface2, soft(lifted)], 4.6, "lighter");
  };
  const primary = brand(light.primary, 0.74);
  const dark = {
    bg, surface, "surface-2": surface2, ink, "ink-soft": inkSoft, line,
    primary,
    "primary-ink": readableOn(primary),
    accent: brand(light.accent, 0.76),
    "accent-2": brand(light["accent-2"], 0.76),
  };
  return dark;
}

function checks(label, t) {
  const soft = mix(t.primary, t.surface, 8);
  const accentSoft = mix(t.accent, t.surface, 16);
  const pairs = [
    ["ink", t.ink, "bg", t.bg], ["ink", t.ink, "surface", t.surface], ["ink", t.ink, "surface-2", t.surface2 ?? t["surface-2"]],
    ["ink", t.ink, "primary tint", soft], ["ink", t.ink, "accent tint", accentSoft],
    ["ink-soft", t["ink-soft"], "bg", t.bg], ["ink-soft", t["ink-soft"], "surface", t.surface],
    ["ink-soft", t["ink-soft"], "surface-2", t["surface-2"]], ["ink-soft", t["ink-soft"], "primary tint", soft],
    ["primary", t.primary, "bg", t.bg], ["primary", t.primary, "surface", t.surface],
    ["primary", t.primary, "surface-2", t["surface-2"]], ["primary", t.primary, "primary tint", soft],
    ["primary-ink", t["primary-ink"], "primary", t.primary],
  ];
  return pairs
    .map(([fa, a, fb, b]) => ({ label, pair: `${fa} on ${fb}`, ratio: contrast(a, b) }))
    .filter((r) => r.ratio < 4.5);
}

const decl = (tokens, extra = "") =>
  TOKENS.map((k) => `  --${k}: ${tokens[k]};`).join("\n") + (tokens.radius ? `\n  --radius: ${tokens.radius};` : "") + extra;

export function buildThemes(config) {
  const failures = [];
  const palettes = {};
  const css = [
    "/* Generated by scripts/build.mjs from data/themes.json. Edit the JSON, not this file.",
    "   Each block is applied with data-theme=\"slug\" on <html> (project pages) or on a card (hub).",
    "   Light is the default. Dark follows the system setting unless the visitor chose a scheme",
    "   with the toggle, which sets data-scheme=\"light\" or \"dark\" on <html>. */",
    "",
  ];

  for (const [slug, theme] of Object.entries(config.themes)) {
    const light = theme.light;
    const dark = { ...deriveDark(light), ...(theme.dark || {}) };
    failures.push(...checks(`${slug} (light)`, light), ...checks(`${slug} (dark)`, dark));
    palettes[slug] = { light, dark };

    const f = theme.fonts;
    const head = `"${f.head}", ${f.headSerif ? SYSTEM_SERIF : SYSTEM_SANS}`;
    const body = `"${f.body}", ${SYSTEM_SANS}`;
    const mono = f.mono ? `"JetBrains Mono", ${SYSTEM_MONO}` : SYSTEM_MONO;
    const sel = `[data-theme="${slug}"]`;
    const darkSel = `html[data-scheme="dark"] ${sel},\nhtml[data-scheme="dark"]${sel}`;
    const systemDarkSel = `  html:not([data-scheme="light"]) ${sel},\n  html:not([data-scheme="light"])${sel}`;

    css.push(
      `${sel} {\n${decl(light)}\n}`,
      `html${sel} {\n  --font-head: ${head};\n  --font-body: ${body};\n  --font-mono: ${mono};\n}`,
      `@media (prefers-color-scheme: dark) {\n${systemDarkSel} {\n${decl(dark).replace(/^/gm, "  ")}\n  }\n}`,
      `${darkSel} {\n${decl(dark)}\n}`,
      "",
    );
  }
  return { css: css.join("\n"), failures, palettes };
}

export function fontFiles(config, slug) {
  const f = config.themes[slug].fonts;
  const file = (name) => {
    const base = name.toLowerCase().replace(/ /g, "-");
    return base === "poppins" ? ["poppins-500", "poppins-600", "poppins-700"] : [base];
  };
  return [...new Set([...file(f.head), ...file(f.body)])];
}
